public class FinalVariable8 {
    /*
    *   FINAL - its a keyword using which we can create constant variables -
    *
    *   class emp {
    *       int id = 10;
    *
    *   }
    *
    *
    *   emp obj1 = new emp();
     *   emp obj2 = new emp();
    *
    * //now both objects can access the id and can change it later so it is not constant yet.
    *
    *   class emp {
     *      final static int id = 10;
     *
     *   }
    *
    *   -use it with class
    *
    * final class emp {
    *   //now this class is final class, which means can not inherited now
    * }
    *
    * -usage with method
    *
    * final static void show(){
    *   //now this method is final method, which can not be overriden by a subclass
    * }
    *
    * -usage with variable
    *
    * final EMP_ID = 10;
    *   //now it can not be re-assigned
    *   //always create final or constant variables in uppercase
    *
    *
    *
    * */
}
