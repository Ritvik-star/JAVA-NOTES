public class WrapperClass7 {
    /*
    * WRAPPER CLASSES -
    *
    *what? - these are object classes of each primitive datatypes -
    * why? - as we know in JAVA we dont have pass by reference but using reference data types we can achieve it
    *           so they helps in that.
    *       - also to work with any collection like arraylist or set we would need wrapper classes only.
    *
    *
    *
    * primitive datatypes                       wrapper class
    *       int                                     INTEGER
    *       char                                    Character
    *       short                                   Short
    *       byte                                    Byte
    *       long                                    Long
    *       float                                   Float
    *       double                                  Double
    *
    *
    *
    *   .e.g....
    *
    *       List<Integer> ls = new ArrayList<>();
    *
    * - these will stored in heap memory only.
    * - whereas primitive datatypes like int, short, char and all others will store in stack memory.
    * -using primitive we can have pass by value only.
    * -using wrapper class or reference data types we can have pass by reference as well.
    *
    *
    *
    *
    *  AUTOBOXING - means, you put small datatype to bigger one, e.g...
    *   int x = 10;
    * Integer x1 = x;   -> here we are wrappng or boxing the small int to bigger Integer wrapper class
    *                 ---->which is why it known as autoboxing.
    *
    * UNBOXING -
    * Integer y = 20;
    * int y1 = y;       ->here we unwrapping or unboxing from wrapper class to primitive
    *                  -->its called unboxing.
    *
    * */
}
